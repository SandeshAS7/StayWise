package com.staywise.amenity;

import com.staywise.common.response.ApiResponse;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

@RestController
@RequestMapping("/api/v1/amenities")
public class AmenityController {

    private final AmenityRepository amenityRepository;

    public AmenityController(AmenityRepository amenityRepository) {
        this.amenityRepository = amenityRepository;
    }

    @GetMapping
    public ResponseEntity<ApiResponse<List<Amenity>>> getAllAmenities() {
        return ResponseEntity.ok(ApiResponse.success(amenityRepository.findAll()));
    }
}
